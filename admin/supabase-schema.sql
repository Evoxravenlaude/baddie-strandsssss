-- ── Who is the admin? ────────────────────────────────────────
create or replace function public.is_admin()
returns boolean language sql stable as $$
  select lower(coalesce(auth.jwt() ->> 'email', '')) = 'baddiestrands@gmail.com'
$$;


-- ── PROFILES (customer name/phone) ───────────────────────────
create table if not exists public.profiles (
  id          uuid references auth.users on delete cascade primary key,
  full_name   text,
  email       text,
  phone       text,
  created_at  timestamptz default now()
);
alter table public.profiles enable row level security;
drop policy if exists "Users can read own profile"   on public.profiles;
drop policy if exists "Users can insert own profile" on public.profiles;
drop policy if exists "Users can update own profile" on public.profiles;
drop policy if exists "Admin reads profiles"         on public.profiles;
create policy "Users can read own profile"   on public.profiles for select using (auth.uid() = id);
create policy "Users can insert own profile" on public.profiles for insert with check (auth.uid() = id);
create policy "Users can update own profile" on public.profiles for update using (auth.uid() = id);
create policy "Admin reads profiles"         on public.profiles for select using (public.is_admin());


-- ── PRODUCTS (managed in the admin dashboard) ───────────────
create table if not exists public.products (
  id           bigint generated by default as identity primary key,
  name         text not null,
  type         text,
  category     text not null default 'wigs',      -- wigs | bundles | extensions
  price        numeric not null,
  old_price    numeric,
  lengths      text[] default '{}',
  colors       text[] default '{}',               -- hex codes
  color_names  text[] default '{}',
  description  text,
  features     text[] default '{}',
  image_url    text,
  stock        integer default 0,
  badge        text,                               -- 'hot' (Bestseller) | 'new' (New in) | null
  visible      boolean default true,
  sort         integer default 0,
  created_at   timestamptz default now()
);
alter table public.products enable row level security;
drop policy if exists "Anyone sees visible products" on public.products;
drop policy if exists "Admin manages products"       on public.products;
create policy "Anyone sees visible products" on public.products for select using (visible = true or public.is_admin());
create policy "Admin manages products"       on public.products for all using (public.is_admin()) with check (public.is_admin());


-- ── ORDERS ───────────────────────────────────────────────────
create table if not exists public.orders (
  id               uuid primary key default gen_random_uuid(),
  user_id          uuid references auth.users on delete set null,
  status           text not null default 'Pending',   -- Pending | Processing | Shipped | Delivered | Cancelled
  total_amount     numeric not null,
  payment_method   text,
  payment_ref      text,
  delivery_state   text,
  delivery_address jsonb,
  created_at       timestamptz default now(),
  updated_at       timestamptz default now()
);
alter table public.orders enable row level security;
drop policy if exists "Users can view own orders" on public.orders;
drop policy if exists "Users can insert orders"   on public.orders;
drop policy if exists "Admin reads orders"        on public.orders;
drop policy if exists "Admin updates orders"      on public.orders;
create policy "Users can view own orders" on public.orders for select using (auth.uid() = user_id);
create policy "Users can insert orders"   on public.orders for insert with check (auth.uid() = user_id);
create policy "Admin reads orders"        on public.orders for select using (public.is_admin());
create policy "Admin updates orders"      on public.orders for update using (public.is_admin()) with check (public.is_admin());


-- ── ORDER ITEMS ──────────────────────────────────────────────
create table if not exists public.order_items (
  id          bigserial primary key,
  order_id    uuid references public.orders on delete cascade not null,
  product_id  integer,
  quantity    integer not null default 1,
  unit_price  numeric not null,
  created_at  timestamptz default now()
);
-- name/length/colour are stored with the item so old orders still read
-- correctly after a product is edited or deleted
alter table public.order_items add column if not exists product_name text;
alter table public.order_items add column if not exists length text;
alter table public.order_items add column if not exists color text;
alter table public.order_items alter column product_id drop not null;
alter table public.order_items enable row level security;
drop policy if exists "Users can view own order items" on public.order_items;
drop policy if exists "Users can insert order items"   on public.order_items;
drop policy if exists "Admin reads order items"        on public.order_items;
create policy "Users can view own order items" on public.order_items for select
  using (exists (select 1 from public.orders where orders.id = order_items.order_id and orders.user_id = auth.uid()));
create policy "Users can insert order items" on public.order_items for insert
  with check (exists (select 1 from public.orders where orders.id = order_items.order_id and orders.user_id = auth.uid()));
create policy "Admin reads order items" on public.order_items for select using (public.is_admin());


-- ── NEWSLETTER SUBSCRIBERS ───────────────────────────────────
create table if not exists public.subscribers (
  id          bigserial primary key,
  email       text unique not null,
  created_at  timestamptz default now()
);
alter table public.subscribers enable row level security;
drop policy if exists "Anyone can subscribe"   on public.subscribers;
drop policy if exists "Admin reads subscribers" on public.subscribers;
create policy "Anyone can subscribe"    on public.subscribers for insert with check (true);
create policy "Admin reads subscribers" on public.subscribers for select using (public.is_admin());


-- ── PRODUCT PHOTOS (storage) ─────────────────────────────────
insert into storage.buckets (id, name, public)
values ('product-images', 'product-images', true)
on conflict (id) do nothing;
drop policy if exists "Public reads product photos" on storage.objects;
drop policy if exists "Admin uploads product photos" on storage.objects;
drop policy if exists "Admin changes product photos" on storage.objects;
drop policy if exists "Admin deletes product photos" on storage.objects;
create policy "Public reads product photos"  on storage.objects for select using (bucket_id = 'product-images');
create policy "Admin uploads product photos" on storage.objects for insert with check (bucket_id = 'product-images' and public.is_admin());
create policy "Admin changes product photos" on storage.objects for update using (bucket_id = 'product-images' and public.is_admin());
create policy "Admin deletes product photos" on storage.objects for delete using (bucket_id = 'product-images' and public.is_admin());


-- ── SPEED ────────────────────────────────────────────────────
create index if not exists orders_user_id_idx    on public.orders(user_id);
create index if not exists orders_created_at_idx on public.orders(created_at desc);
create index if not exists orders_status_idx     on public.orders(status);
create index if not exists order_items_order_idx on public.order_items(order_id);
create index if not exists products_visible_idx  on public.products(visible, sort);
