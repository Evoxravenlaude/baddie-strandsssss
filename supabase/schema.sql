-- ── PRODUCTS (managed in the admin dashboard) ───────────────
create table if not exists public.products (
  id           bigint generated by default as identity primary key,
  name         text not null,
  type         text,
  category     text not null default 'wigs',      -- wigs | bundles | extensions
  price        numeric not null,
  old_price    numeric,
  lengths      text[] default '{}',
  colors       text[] default '{}',               -- hex codes
  color_names  text[] default '{}',
  description  text,
  features     text[] default '{}',
  image_url    text,
  stock        integer default 0,
  badge        text,                               -- 'hot' (Bestseller) | 'new' (New in) | null
  visible      boolean default true,
  sort         integer default 0,
  created_at   timestamptz default now()
);
alter table public.products enable row level security;
drop policy if exists "Anyone sees visible products" on public.products;
drop policy if exists "Admin manages products"       on public.products;
create policy "Anyone sees visible products" on public.products for select using (visible = true or public.is_admin());
create policy "Admin manages products"       on public.products for all using (public.is_admin()) with check (public.is_admin());


-- ── ORDERS ───────────────────────────────────────────────────
create table if not exists public.orders (
  id               uuid primary key default gen_random_uuid(),
  user_id          uuid references auth.users on delete set null,
  status           text not null default 'Pending',   -- Pending | Processing | Shipped | Delivered | Cancelled
